test_that("latent-state public inputs fail clearly", {
  P <- matrix(c(.9,.1,.1,.9),2,byrow=TRUE)
  expect_error(ms_stationary(matrix(1,2,2)),"row-stochastic")
  expect_error(ms_stationary(diag(2)),"unique")
  expect_equal(ms_stationary(matrix(1)),1)
  expect_equal(ms_stationary(matrix(c(1,0,.2,.8),2,byrow=TRUE)),c(1,0))
  expect_error(ms_filter(c(1,NA),c(-1,1),c(0,0),c(1,1),P),"finite")
  expect_error(ms_filter(c(1,2),c(-1,1),c(0,0),c(1,1),P,prior=c(NA,1)),"initial")
  expect_error(ms_filter(1,c(-1,1),c(0,0),c(1,1),P,smooth=NA),"logical")
  expect_error(ms_simulate(3,c(-1,1),c(0,0),c(1,1),P,burn=c(1,2)),"integers")
  expect_error(ms_forecast_moments(0,c(.5,.5),c(-1,1),c(0,0),c(1,1),P,horizon=NA),"forecast")
  expect_error(ms_forecast_draws(0,c(.5,.5),c(-1,1),c(0,0),c(1,1),P,draws=Inf),"forecast")
  expect_error(fit_msar(rep(1,40),maxit=NA),"controls")
  expect_error(fit_msar(rep(1,40),tol=0),"controls")
  expect_error(kf_filter(1:3,matrix(1),matrix(.8),matrix(-1),matrix(1),0,matrix(1)),"semidefinite")
  expect_error(kf_filter(1:3,matrix(1),matrix(.8),matrix(1),matrix(1),0,matrix(1),smooth=NA),"logical")
  expect_error(kf_filter(1:3,matrix(1),matrix(.8),matrix(1),matrix(1),0,matrix(1),d=c(1,NA,2)),"offset")
  expect_error(kf_forecast(0,matrix(1),1,matrix(.8),matrix(1),matrix(1)),"Z must")
  expect_error(kf_stationary_cov(matrix(1),matrix(1)),"stable")
  expect_error(kf_fit_local_level(1:30,variance_floor=c(1,2)),"inputs")
})

test_that("EM initialization respects user-specified tighter constraints", {
  set.seed(19)
  P<-matrix(c(.6,.4,.4,.6),2,byrow=TRUE)
  y<-ms_simulate(180,c(-1,1),c(.1,.1),c(.8,.8),P,burn=200)$y
  fit<-fit_msar(y,starts=2,phi_bound=.15,probability_floor=.25,
                sd_floor=.6*sd(y),maxit=1200)
  expect_true(fit$converged)
  expect_true(all(fit$P>=.25 & fit$P<=.75))
  expect_true(all(abs(fit$phi)<=.15))
  expect_true(all(fit$sigma>=.6*sd(y)))
  expect_true(all(diff(fit$history)> -1e-6))
})
